/**
 * Generate dist/sw.js after the build: a small service worker that makes the
 * installed app work offline. The precache list and version come from the
 * built files, so every daily redeploy ships a new version automatically.
 *
 *   navigation → network first (fresh daily data), cached page when offline
 *   built assets → cache first (file names are content-hashed)
 *   feeds → always network (calendar apps and readers need current data)
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = resolve(ROOT, process.argv[2] ?? 'dist');

const walk = (dir: string): string[] =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

const files = walk(DIST)
  .map((p) => relative(DIST, p).split('\\').join('/'))
  .filter((f) => !f.startsWith('feeds/') && f !== 'sw.js' && !f.endsWith('.map'))
  .sort();
const version = createHash('sha256').update(files.map((f) => f + readFileSync(join(DIST, f)).length).join('|')).update(readFileSync(join(DIST, 'index.html'))).update(readFileSync(fileURLToPath(import.meta.url))).digest('hex').slice(0, 12);
const precache = ['./', ...files.map((f) => `./${f}`)];

const sw = `/* IMMCA service worker — generated by scripts/build-sw.ts, version ${version} */
const CACHE = 'immca-${version}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('immca-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin || url.pathname.includes('/feeds/')) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./', { ignoreVary: true }).then((r) => r || caches.match('./index.html', { ignoreVary: true }))),
    );
    return;
  }
  // ignoreVary: precached copies were stored without an Origin header, module/CSS requests send one.
  event.respondWith(caches.match(req, { ignoreVary: true }).then((hit) => hit || fetch(req)));
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`sw.js ${version}: ${precache.length} files precached`);
